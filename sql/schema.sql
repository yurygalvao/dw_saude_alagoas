-- FATO_INTERNACAO - grão: 1 registro de AIH paga (arquivo RD do SIH).
-- Dimensões degeneradas: NUM_AIH, TIPO_AIH (1 = normal, 5 = longa
-- permanência), SEQ_AIH5 e ANO_MES_CMPT (competência de processamento).
CREATE TABLE FATO_INTERNACAO (
    SK_TEMPO_INTERNACAO       NUMBER(8)  NOT NULL,
    SK_TEMPO_SAIDA            NUMBER(8)  NOT NULL,
    SK_MUNICIPIO_RESIDENCIA   NUMBER(10) NOT NULL,
    SK_MUNICIPIO_ATENDIMENTO  NUMBER(10) NOT NULL,
    SK_ESTABELECIMENTO        NUMBER(10) NOT NULL,
    SK_PROCEDIMENTO           NUMBER(10) NOT NULL,
    SK_CID                    NUMBER(10) NOT NULL,
    SK_ESPECIALIDADE          NUMBER(10) NOT NULL,
    SK_CARATER                NUMBER(10) NOT NULL,
    SK_PERFIL                 NUMBER(10) NOT NULL,
    NUM_AIH                   VARCHAR2(13 CHAR) NOT NULL,
    TIPO_AIH                  VARCHAR2(1 CHAR)  NOT NULL,
    SEQ_AIH5                  VARCHAR2(3 CHAR)  NOT NULL,
    ANO_MES_CMPT              VARCHAR2(7 CHAR)  NOT NULL,
    QTD_INTERNACAO            NUMBER(1)     DEFAULT 1 NOT NULL,
    QTD_DIAS_PERMANENCIA      NUMBER(6)     DEFAULT 0 NOT NULL,
    VL_TOTAL                  NUMBER(15,2)  DEFAULT 0 NOT NULL,
    QTD_OBITO                 NUMBER(1)     DEFAULT 0 NOT NULL,
    CONSTRAINT PK_FATO_INTERNACAO PRIMARY KEY
        (SK_ESTABELECIMENTO, NUM_AIH, TIPO_AIH, SEQ_AIH5, ANO_MES_CMPT, SK_TEMPO_SAIDA)
        USING INDEX TABLESPACE TS_DW_INDICES,
    CONSTRAINT FK_FATO_INTERNACAO_TEMPO_INT   FOREIGN KEY (SK_TEMPO_INTERNACAO)      REFERENCES DIM_TEMPO (SK_TEMPO),
    CONSTRAINT FK_FATO_INTERNACAO_TEMPO_SAI   FOREIGN KEY (SK_TEMPO_SAIDA)           REFERENCES DIM_TEMPO (SK_TEMPO),
    CONSTRAINT FK_FATO_INTERNACAO_MUN_RES     FOREIGN KEY (SK_MUNICIPIO_RESIDENCIA)  REFERENCES DIM_MUNICIPIO (SK_MUNICIPIO),
    CONSTRAINT FK_FATO_INTERNACAO_MUN_ATD     FOREIGN KEY (SK_MUNICIPIO_ATENDIMENTO) REFERENCES DIM_MUNICIPIO (SK_MUNICIPIO),
    CONSTRAINT FK_FATO_INTERNACAO_ESTAB       FOREIGN KEY (SK_ESTABELECIMENTO)       REFERENCES DIM_ESTABELECIMENTO (SK_ESTABELECIMENTO),
    CONSTRAINT FK_FATO_INTERNACAO_PROCED      FOREIGN KEY (SK_PROCEDIMENTO)          REFERENCES DIM_PROCEDIMENTO (SK_PROCEDIMENTO),
    CONSTRAINT FK_FATO_INTERNACAO_CID         FOREIGN KEY (SK_CID)                   REFERENCES DIM_CID (SK_CID),
    CONSTRAINT FK_FATO_INTERNACAO_ESPEC       FOREIGN KEY (SK_ESPECIALIDADE)         REFERENCES DIM_ESPECIALIDADE (SK_ESPECIALIDADE),
    CONSTRAINT FK_FATO_INTERNACAO_CARATER     FOREIGN KEY (SK_CARATER)               REFERENCES DIM_CARATER_ATENDIMENTO (SK_CARATER),
    CONSTRAINT FK_FATO_INTERNACAO_PERFIL      FOREIGN KEY (SK_PERFIL)                REFERENCES DIM_PERFIL_PACIENTE (SK_PERFIL)
)
COMPRESS;

-- FATO_PRODUCAO_AMBULATORIAL - grão: competência x município de residência x
-- município de atendimento x estabelecimento x procedimento (registros do SIA
-- somados nesse grão). PK = conjunto das FKs.
CREATE TABLE FATO_PRODUCAO_AMBULATORIAL (
    SK_TEMPO_COMPETENCIA      NUMBER(8)  NOT NULL,
    SK_MUNICIPIO_RESIDENCIA   NUMBER(10) NOT NULL,
    SK_MUNICIPIO_ATENDIMENTO  NUMBER(10) NOT NULL,
    SK_ESTABELECIMENTO        NUMBER(10) NOT NULL,
    SK_PROCEDIMENTO           NUMBER(10) NOT NULL,
    QTD_REGISTROS             NUMBER(10)    DEFAULT 0 NOT NULL,
    QTD_APRESENTADA           NUMBER(12)    DEFAULT 0 NOT NULL,
    QTD_APROVADA              NUMBER(12)    DEFAULT 0 NOT NULL,
    VL_APRESENTADO            NUMBER(15,2)  DEFAULT 0 NOT NULL,
    VL_APROVADO               NUMBER(15,2)  DEFAULT 0 NOT NULL,
    CONSTRAINT PK_FATO_PRODUCAO_AMBULATORIAL PRIMARY KEY
        (SK_TEMPO_COMPETENCIA, SK_MUNICIPIO_RESIDENCIA, SK_MUNICIPIO_ATENDIMENTO,
         SK_ESTABELECIMENTO, SK_PROCEDIMENTO)
        USING INDEX LOCAL TABLESPACE TS_DW_INDICES,
    CONSTRAINT FK_FATO_PROD_AMB_TEMPO    FOREIGN KEY (SK_TEMPO_COMPETENCIA)     REFERENCES DIM_TEMPO (SK_TEMPO),
    CONSTRAINT FK_FATO_PROD_AMB_MUN_RES  FOREIGN KEY (SK_MUNICIPIO_RESIDENCIA)  REFERENCES DIM_MUNICIPIO (SK_MUNICIPIO),
    CONSTRAINT FK_FATO_PROD_AMB_MUN_ATD  FOREIGN KEY (SK_MUNICIPIO_ATENDIMENTO) REFERENCES DIM_MUNICIPIO (SK_MUNICIPIO),
    CONSTRAINT FK_FATO_PROD_AMB_ESTAB    FOREIGN KEY (SK_ESTABELECIMENTO)       REFERENCES DIM_ESTABELECIMENTO (SK_ESTABELECIMENTO),
    CONSTRAINT FK_FATO_PROD_AMB_PROCED   FOREIGN KEY (SK_PROCEDIMENTO)          REFERENCES DIM_PROCEDIMENTO (SK_PROCEDIMENTO)
)
COMPRESS
PARTITION BY RANGE (SK_TEMPO_COMPETENCIA) INTERVAL (100)
    (PARTITION P_ANTERIOR VALUES LESS THAN (20000101));

