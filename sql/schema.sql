-- ============================================================================
-- DATA WAREHOUSE SAÚDE ALAGOAS (SIH / SIA / CNES - DATASUS) - 2023 e 2024
-- Banco: Oracle 23 Free | Owner/schema: DW_ALAGOAS
-- Tablespaces (criados em 00_init_owner.sql):
--   TS_DW_DADOS   -> tabelas      TS_DW_INDICES -> índices (PK, UK, bitmap)
--
-- Camadas: BRONZE (cópia fiel da origem) -> SILVER (limpa e padronizada)
--          -> GOLD (star schema) -> MART (uma tabela por pergunta de negócio)
--
-- Este arquivo é a ÚNICA fonte do DDL. A task "aplicar_schema" da DAG o executa
-- conectada como DW_ALAGOAS e ignora "objeto já existe" (idempotente).
--
-- Padrão de nomes
--   Tabelas : BRONZE_*, SILVER_*, DIM_*, FATO_*, MART_Pnn_*
--   Colunas : SK_ (surrogate key), COD_ (código natural), NOME_/DESCRICAO_,
--             DT_ (data), NR_ (número), QTD_ (quantidade), VL_ (valor R$),
--             FLG_ (S/N), PCT_ (percentual), TIPO_ (classificação)
--   Constraints: PK_<tabela>, UK_<tabela>_<coluna>, FK_<fato>_<dimensão>, CK_
--   Índices bitmap: BX_<fato>_<coluna>   Sequences: SEQ_<dimensão>
--
-- Performance
--   * COMPRESS nas tabelas grandes + carga direct-path (APPEND).
--   * Bronze SIH/SIA/LEITOS particionadas por ano: recarga idempotente com
--     TRUNCATE PARTITION.
--   * FATO_PRODUCAO_AMBULATORIAL particionada por mês (INTERVAL): partition
--     pruning nas consultas por período.
--   * Índices bitmap nas FKs das fatos (padrão de star schema) e nenhum
--     índice em bronze/silver/marts (lidas por full scan ou pequenas).
-- ============================================================================


